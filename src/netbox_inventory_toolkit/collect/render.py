"""Deterministic YAML rendering for the generated inventory layer."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

from .log import get_logger

log = get_logger(__name__)


def write_yaml(
    path: Path,
    sections: dict[str, Any],
    title: str,
    *,
    sources: list[str] | None = None,
) -> None:
    source_text = ", ".join(sources) if sources else "the manual inventory only"
    header = (
        f"# Generated by netbox-inventory-toolkit from {source_text}.\n"
        f"# Do not hand-edit this file.\n"
        f"# {title}\n\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        header
        + yaml.safe_dump(
            {"layer": "generated", **sections},
            sort_keys=False,
            allow_unicode=True,
        ),
        encoding="utf-8",
    )
    details = ", ".join(
        f"{key}={len(value)}"
        for key, value in sections.items()
        if isinstance(value, list)
    )
    log.info("Wrote %s%s", path, f" ({details})" if details else "")
